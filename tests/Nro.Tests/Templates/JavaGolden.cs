using System.Text.Json;

namespace Nro.Tests.Templates;

internal sealed record JavaParam(string Name, string Type);

internal sealed record JavaField(string Name, string Type, string[] Modifiers)
{
    public bool IsStatic => Modifiers.Contains("static");

    public bool IsFinal => Modifiers.Contains("final");
}

internal sealed record JavaCtor(string[] Modifiers, JavaParam[] Parameters);

internal sealed record JavaMethod(string Name, string[] Modifiers, string ReturnType, JavaParam[] Parameters)
{
    public bool IsStatic => Modifiers.Contains("static");
}

/// <summary>The result of REALLY calling a Java constructor with sample arguments: <c>Args</c> is the recipe for building the arguments, <c>State</c> is every field after construction.</summary>
internal sealed record JavaInstance(string Sample, string[] CtorTypes, JsonElement Args, JsonElement State);

internal sealed record JavaClass(
    string Name,
    string SimpleName,
    string? Enclosing,
    string Kind,
    string[] Modifiers,
    string? Superclass,
    string[] Interfaces,
    JavaField[] Fields,
    JavaCtor[] Ctors,
    JavaMethod[] Methods,
    string[] Nested,
    JavaInstance[] Instances)
{
    public IEnumerable<JavaField> InstanceFields => Fields.Where(f => !f.IsStatic);
}

/// <summary>
/// The contents of <c>tests/golden/templates.json</c>, generated by <c>tools/templates/regen.py</c> by compiling and running
/// the Java files themselves (reflection + real constructor calls). Do not edit that file by hand.
/// </summary>
internal sealed class JavaGolden
{
    private static readonly Lazy<JavaGolden> Shared = new(() => Load(TestPaths.Golden("templates.json")));

    // Keep the JsonDocument alive for the whole lifetime of the process because the JsonElement values in JavaInstance point into it.
    private readonly JsonDocument _document;

    private JavaGolden(JsonDocument document, JavaClass[] classes, string[] sourcePaths, string[] sourceHashes)
    {
        _document = document;
        Classes = classes;
        SourcePaths = sourcePaths;
        SourceHashes = sourceHashes;
        ByName = classes.ToDictionary(c => c.Name, StringComparer.Ordinal);
    }

    public static JavaGolden Instance => Shared.Value;

    public IReadOnlyList<JavaClass> Classes { get; }

    public IReadOnlyDictionary<string, JavaClass> ByName { get; }

    public IReadOnlyList<string> SourcePaths { get; }

    public IReadOnlyList<string> SourceHashes { get; }

    public string Schema => _document.RootElement.GetProperty("schema").GetString() ?? "";

    private static JavaGolden Load(string path)
    {
        if (!File.Exists(path))
        {
            throw new FileNotFoundException("Missing golden templates.json; regenerate it with tools/templates/regen.py", path);
        }

        JsonDocument doc = JsonDocument.Parse(File.ReadAllBytes(path));
        JsonElement root = doc.RootElement;

        JsonElement[] sources = root.GetProperty("sources").EnumerateArray().ToArray();
        JavaClass[] classes = root.GetProperty("classes").EnumerateArray().Select(ParseClass).ToArray();
        return new JavaGolden(
            doc,
            classes,
            sources.Select(s => Str(s, "path")).ToArray(),
            sources.Select(s => Str(s, "sha256")).ToArray());
    }

    private static JavaClass ParseClass(JsonElement c)
    {
        return new JavaClass(
            Str(c, "name"),
            Str(c, "simpleName"),
            OptStr(c, "enclosing"),
            Str(c, "kind"),
            StrArray(c, "modifiers"),
            OptStr(c, "superclass"),
            StrArray(c, "interfaces"),
            c.GetProperty("fields").EnumerateArray()
                .Select(f => new JavaField(Str(f, "name"), Str(f, "type"), StrArray(f, "modifiers"))).ToArray(),
            c.GetProperty("constructors").EnumerateArray()
                .Select(k => new JavaCtor(StrArray(k, "modifiers"), Params(k))).ToArray(),
            c.GetProperty("methods").EnumerateArray()
                .Select(m => new JavaMethod(Str(m, "name"), StrArray(m, "modifiers"), Str(m, "returnType"), Params(m))).ToArray(),
            StrArray(c, "nested"),
            c.GetProperty("instances").EnumerateArray()
                .Select(i => new JavaInstance(Str(i, "sample"), StrArray(i, "ctor"), i.GetProperty("args"), i.GetProperty("state"))).ToArray());
    }

    private static JavaParam[] Params(JsonElement owner)
    {
        return owner.GetProperty("parameters").EnumerateArray()
            .Select(p => new JavaParam(Str(p, "name"), Str(p, "type"))).ToArray();
    }

    private static string Str(JsonElement e, string property)
    {
        return e.GetProperty(property).GetString()
            ?? throw new InvalidDataException($"golden: '{property}' is null");
    }

    private static string? OptStr(JsonElement e, string property)
    {
        JsonElement v = e.GetProperty(property);
        return v.ValueKind == JsonValueKind.Null ? null : v.GetString();
    }

    private static string[] StrArray(JsonElement e, string property)
    {
        return e.GetProperty(property).EnumerateArray()
            .Select(x => x.GetString() ?? throw new InvalidDataException($"golden: null element in '{property}'")).ToArray();
    }
}
