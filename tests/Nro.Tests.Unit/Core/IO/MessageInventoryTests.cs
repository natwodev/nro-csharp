    /// <summary>Public methods that exist only in Message.java and not in IMessage.java.</summary>
    private static readonly MemberSpec[] MessageOnlyMembers =
    [
        M("void writeByteToLong(long,boolean)", "WriteByteToLong", typeof(void), typeof(long), typeof(bool)),
        M("void writeCris(long,boolean)", "WriteCris", typeof(void), typeof(long), typeof(bool)),
        M("void writeShortToLong(long,boolean)", "WriteShortToLong", typeof(void), typeof(long), typeof(bool)),
    ];

    private static string Describe(MemberSpec s) =>
        $"{s.Returns.Name} {s.Cs}({string.Join(", ", s.Parameters.Select(p => p.Name))})  <= {s.Java}";

    private static List<string> Missing(Type type, IEnumerable<MemberSpec> specs)
    {
        var problems = new List<string>();
        foreach (MemberSpec spec in specs)
        {
            MethodInfo? method = type.GetMethod(spec.Cs, BindingFlags.Public | BindingFlags.Instance, binder: null, types: spec.Parameters, modifiers: null);
            if (method is null)
            {
                problems.Add($"{type.Name}: missing {Describe(spec)}");
            }
            else if (method.ReturnType != spec.Returns)
            {
                problems.Add($"{type.Name}: {spec.Cs} returns {method.ReturnType.Name}, expected {spec.Returns.Name} (<= {spec.Java})");
            }
        }

        return problems;
    }

    [Fact]
    public void IMessage_has_exactly_the_35_methods_of_IMessage_java_no_more_no_fewer()
    {
        List<string> problems = Missing(typeof(IMessage), InterfaceMembers);

        Assert.True(problems.Count == 0, string.Join(Environment.NewLine, problems));
        Assert.Equal(35, InterfaceMembers.Length);
        Assert.Equal(InterfaceMembers.Length, typeof(IMessage).GetMethods().Length);
        Assert.Empty(typeof(IMessage).GetProperties());
        Assert.Empty(typeof(IMessage).GetInterfaces());
    }

    [Fact]
    public void Message_implements_all_35_IMessage_methods_plus_its_own_3()
    {
        List<string> problems = Missing(typeof(Message), InterfaceMembers.Concat(MessageOnlyMembers));

        Assert.True(problems.Count == 0, string.Join(Environment.NewLine, problems));
        Assert.Equal(3, MessageOnlyMembers.Length);
        Assert.True(typeof(IMessage).IsAssignableFrom(typeof(Message)));

        // every public method (declared directly) of Message is in the two tables: there are no extra methods
        string[] declared = typeof(Message)
            .GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
            .Where(m => !m.IsSpecialName)
            .Select(m => m.Name + "(" + string.Join(",", m.GetParameters().Select(p => p.ParameterType.Name)) + ")")
            .OrderBy(x => x, StringComparer.Ordinal)
            .ToArray();
        string[] expected = InterfaceMembers.Concat(MessageOnlyMembers)
            .Select(s => s.Cs + "(" + string.Join(",", s.Parameters.Select(p => p.Name)) + ")")
            .OrderBy(x => x, StringComparer.Ordinal)
            .ToArray();
        Assert.Equal(expected, declared);
    }

    [Fact]
    public void Message_has_a_writable_sbyte_Command_and_3_constructors_with_the_right_signatures()
    {
        PropertyInfo? command = typeof(Message).GetProperty(nameof(Message.Command));

        Assert.NotNull(command);
        Assert.Equal(typeof(sbyte), command!.PropertyType);
        Assert.True(command.CanRead && command.CanWrite);
        Assert.NotNull(typeof(Message).GetConstructor([typeof(int)]));
        Assert.NotNull(typeof(Message).GetConstructor([typeof(sbyte)]));
        Assert.NotNull(typeof(Message).GetConstructor([typeof(sbyte), typeof(byte[])]));
        Assert.Equal(3, typeof(Message).GetConstructors().Length);
    }

    [Fact]
    public void ReadImage_and_WriteImage_are_deliberately_not_ported_because_nothing_calls_them()
    {
        Assert.Null(typeof(IMessage).GetMethod("ReadImage"));
        Assert.Null(typeof(IMessage).GetMethod("WriteImage"));
        Assert.Null(typeof(Message).GetMethod("ReadImage"));
        Assert.Null(typeof(Message).GetMethod("WriteImage"));
    }

    [Fact]
    public void Message_and_IMessage_do_not_extend_IDisposable_so_using_does_not_accidentally_call_Dispose()
    {
        Assert.False(typeof(IDisposable).IsAssignableFrom(typeof(IMessage)));
        Assert.False(typeof(IDisposable).IsAssignableFrom(typeof(Message)));
    }

