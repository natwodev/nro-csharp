/// <summary>
/// Characterization of <see cref="NPoint"/> against the ORIGINAL Java <c>NPoint.java</c>. <c>npoint-characterization.json</c> holds ~1100 scenarios; for each, the inputs (equipment, flags, skills,
/// pet, server settings) and, per operation, what the original produced: the return value, EVERY public field of the object (stored sparsely against a table of defaults), the values it wrote
/// into other objects, and the calls it made to services. It was generated by <c>port-csharp/tools/npoint/run_npoint_characterization.py</c> from the harness in <c>NPointHarness/</c>
/// (the original NPoint.java compiled unchanged against test doubles; random draws use <c>new Random(seed)</c>, which <see cref="SeededRandomProvider"/> reproduces bit for bit).
/// This test replays the inputs on the port and compares everything.
/// </summary>
public class NPointCharacterizationTests
{
    /// <summary>The fake "now" of the replay. The Java run used the real clock, so scenarios only use expiry times far from any real clock value (1 and 2^61).</summary>
    private const long NowMs = 1_700_000_000_000L;

    private static readonly Lazy<JsonDocument> Corpus = new(() => JsonDocument.Parse(File.ReadAllBytes(Path.Combine(TestPaths.ProjectDirectory("Nro.Tests.Unit"), "Game", "Players", "Stats", "npoint-characterization.json"))));

    public static IEnumerable<object[]> CaseNames()
    {
        foreach (JsonElement c in Corpus.Value.RootElement.GetProperty("cases").EnumerateArray())
        {
            yield return [c.GetProperty("name").GetString()!];
        }
    }

    [Fact]
    public void Corpus_has_at_least_fifty_cases_and_names_are_unique()
    {
        JsonElement cases = Corpus.Value.RootElement.GetProperty("cases");
        Assert.True(cases.GetArrayLength() >= 50, "E-01 asks for at least 50 characterization cases");
        HashSet<string> names = [];
        foreach (JsonElement c in cases.EnumerateArray())
        {
            Assert.True(names.Add(c.GetProperty("name").GetString()!), "duplicate case name " + c.GetProperty("name").GetString());
        }
    }

    [Fact]
    public void Corpus_records_the_original_sources_and_jdk()
    {
        JsonElement meta = Corpus.Value.RootElement.GetProperty("meta");
        Assert.Contains("17.", meta.GetProperty("jdk").GetString(), StringComparison.Ordinal);
        Assert.Equal(64, meta.GetProperty("originalSources").GetProperty("nro/player/NPoint.java").GetString()!.Length);
    }

    [Fact]
    public void Corpus_was_generated_from_the_current_java_source_when_the_source_tree_is_next_to_the_repo()
    {
        string java = Path.GetFullPath(Path.Combine(TestPaths.RepoRoot(), "..", "source-game", "SRC_6", "AWN_Version", "AWN_Version", "src"));
        if (!Directory.Exists(java))
        {
            return; // the Java tree is not on this machine: nothing to compare with
        }

        JsonElement hashes = Corpus.Value.RootElement.GetProperty("meta").GetProperty("originalSources");
        foreach (JsonProperty entry in hashes.EnumerateObject())
        {
            string file = Path.Combine(java, entry.Name.Replace('/', Path.DirectorySeparatorChar));
            string actual = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(file))).ToLowerInvariant();
            Assert.True(actual == entry.Value.GetString(), $"{entry.Name} changed since npoint-characterization.json was generated: run port-csharp/tools/npoint/run_npoint_characterization.py again");
        }
    }

    [Theory]
    [MemberData(nameof(CaseNames))]
    public void Replay_matches_original(string name)
    {
        JsonElement scenario = Corpus.Value.RootElement.GetProperty("cases").EnumerateArray().First(c => c.GetProperty("name").GetString() == name);
        JsonElement defaults = Corpus.Value.RootElement.GetProperty("defaults");

        ManualTimeProvider time = new(DateTimeOffset.FromUnixTimeMilliseconds(NowMs));
        NPointScenarioHost host = new();
        VietnamClock clock = new(time);
        Player main = host.Build(scenario.GetProperty("main"), null, n =>
        {
            n.Host = host;
            n.Clock = clock;
        });
        ApplyServer(host, scenario.GetProperty("server"));

        int index = 0;
        JsonElement ops = scenario.GetProperty("ops");
        JsonElement results = scenario.GetProperty("results");
        for (int i = 0; i < ops.GetArrayLength(); i++)
        {
            JsonElement op = ops[i];
            JsonElement expected = results[i];
            string opName = op.GetProperty("op").GetString()!;
            long seed = op.TryGetProperty("seed", out JsonElement s) ? s.GetInt64() : 1000 + index;
            main.NPoint.Rand = new RandomUtil(new SeededRandomProvider(seed));
            host.Log.Clear();

            object? ret = null;
            Exception? thrown = null;
            try
            {
                ret = Execute(main, host, op, opName);
            }
            catch (Exception e) when (e is NullReferenceException or DivideByZeroException or ArgumentOutOfRangeException)
            {
                thrown = e;
            }

            string where = $"{name} op#{i} {opName}";
            if (expected.TryGetProperty("ex", out JsonElement ex))
            {
                Assert.True(thrown is not null, $"{where}: Java threw {ex.GetString()}, the port did not");
                Assert.Equal(ExpectedException(ex.GetString()!), thrown!.GetType());
            }
            else
            {
                Assert.True(thrown is null, $"{where}: the port threw {thrown}");
            }

            if (expected.TryGetProperty("ret", out JsonElement r))
            {
                CompareReturn(where, r, ret);
            }

            CompareState(where, defaults, expected.GetProperty("state"), main.NPoint);
            if (expected.TryGetProperty("detuState", out JsonElement ds))
            {
                CompareState(where + " (pet)", defaults, ds, main.Pet!.NPoint);
            }

            CompareEffects(where, expected.GetProperty("effects"), host.StoreOf(main));
            List<string> expectedLog = [.. expected.GetProperty("host").EnumerateArray().Select(x => x.GetString()!)];
            Assert.True(expectedLog.SequenceEqual(host.Log), $"{where}: calls to services differ.\nJava: {string.Join(" | ", expectedLog)}\nPort: {string.Join(" | ", host.Log)}");
            index++;
        }
    }

    private static Type ExpectedException(string javaName) => javaName switch
    {
        "NullPointerException" => typeof(NullReferenceException),
        "ArithmeticException" => typeof(DivideByZeroException),
        "IndexOutOfBoundsException" => typeof(ArgumentOutOfRangeException),
        _ => throw new InvalidOperationException("no mapping for " + javaName),
    };

    private static void ApplyServer(NPointScenarioHost host, JsonElement server)
    {
        foreach (JsonElement kv in server.GetProperty("sets").EnumerateArray())
        {
            string path = kv[0].GetString()!;
            JsonElement v = kv[1];
            switch (path)
            {
                case "readInt":
                    host.ReadInt = v.GetBoolean();
                    break;
                case "rateExp":
                    host.RateExp = v.GetInt32();
                    break;
                case "womansDay":
                    host.WomansDay = v.GetBoolean();
                    break;
                case "wdHp":
                    host.WdHp = v.GetInt32();
                    break;
                case "wdMp":
                    host.WdMp = v.GetInt32();
                    break;
                case "wdDame":
                    host.WdDame = v.GetInt32();
                    break;
                default:
                    throw new InvalidOperationException("unknown server setting " + path);
            }
        }

        foreach (JsonElement a in server.GetProperty("attrs").EnumerateArray())
        {
            host.Attributes[a[0].GetInt32()] = (a[1].GetInt32(), a[2].GetBoolean());
        }

        foreach (JsonElement w in server.GetProperty("whis").EnumerateArray())
        {
            host.Whis.Add(w.GetInt64());
        }

        foreach (JsonElement l in server.GetProperty("limits").EnumerateArray())
        {
            host.Limits[l[0].GetInt32()] = new PowerLimitInfo(l[1].GetInt64(), l[2].GetInt64(), l[3].GetInt64(), l[4].GetInt64(), l[5].GetInt32(), l[6].GetInt32());
        }
    }

    private static object? Execute(Player main, NPointScenarioHost host, JsonElement op, string name)
    {
        NPoint n = main.NPoint;
        switch (name)
        {
            case "calPoint":
                n.CalPoint();
                return null;
            case "setBasePoint":
                n.SetBasePoint();
                return null;
            case "initPowerLimit":
                n.InitPowerLimit();
                return n.PowerLimit?.Power;
            case "getDameAttack":
                return n.GetDamageAttack(op.GetProperty("isMob").GetBoolean());
            case "calSucManhTiemNang":
                return n.CalculatePowerPotential(op.GetProperty("arg").GetInt64());
            case "calSubTNSM":
                return n.CalculatePowerPotentialReduction(op.GetProperty("arg").GetInt64());
            case "increasePoint":
                n.IncreasePoint((sbyte)op.GetProperty("type").GetInt32(), (short)op.GetProperty("point").GetInt32(), op.GetProperty("manual").GetBoolean());
                return null;
            case "getFullTN":
                return n.GetFullTN();
            case "update":
                n.Update();
                return null;
            case "setHP":
                n.SetHP(op.GetProperty("arg").GetInt64());
                return null;
            case "setHp":
                n.SetHp(op.GetProperty("arg").GetInt64());
                return null;
            case "setMP":
                n.SetMP(op.GetProperty("arg").GetInt64());
                return null;
            case "setMp":
                n.SetMp(op.GetProperty("arg").GetInt64());
                return null;
            case "addHp":
                n.AddHp(op.GetProperty("arg").GetInt64());
                return null;
            case "addMp":
                n.AddMp(op.GetProperty("arg").GetInt64());
                return null;
            case "subHP":
                n.SubHP(ParseDouble(op.GetProperty("arg").GetString()!));
                return null;
            case "subMP":
                n.SubMP(op.GetProperty("arg").GetInt64());
                return null;
            case "getHP":
                return n.GetHP();
            case "getMP":
                return n.GetMP();
            case "getCurrPercentHP":
                return n.GetCurrentHpPercent();
            case "getCurrPercentMP":
                return n.GetCurrentMpPercent();
            case "setFullHpMp":
                n.SetFullHpMp();
                return null;
            case "subSucManh":
                n.SubtractPower(op.GetProperty("arg").GetInt64());
                return null;
            case "subTiemNang":
                n.SubtractPotential(op.GetProperty("arg").GetInt64());
                return null;
            case "subSucManhTiemNang":
                n.SubtractPowerPotential(op.GetProperty("arg").GetInt64());
                return null;
            case "powerUp":
                n.PowerUp(op.GetProperty("arg").GetInt64());
                return null;
            case "settlGold":
                n.ApplyIntrinsicGoldPercent();
                return null;
            case "subDameInjureWithDeff":
                return n.ReduceDamageByDefense(ParseDouble(op.GetProperty("arg").GetString()!));
            case "getTileHutHp":
                return n.GetHpAbsorptionPercent(op.GetProperty("isMob").GetBoolean());
            case "getPowerLimit":
                return n.GetPowerLimit();
            case "getPowerNextLimit":
                return n.GetPowerNextLimit();
            case "canOpenPower":
                return n.CanOpenPower();
            case "calPercent":
                return n.CalculatePercent(op.GetProperty("a").GetInt64(), op.GetProperty("b").GetInt64());
            case "set":
                host.ApplySet(host.StoreOf(main), op.GetProperty("path").GetString()!, op.GetProperty("value"));
                return null;
            default:
                throw new InvalidOperationException("unknown op " + name);
        }
    }

    private static double ParseDouble(string text) => text switch
    {
        "NaN" => double.NaN,
        _ => double.Parse(text, CultureInfo.InvariantCulture),
    };

    private static void CompareReturn(string where, JsonElement expected, object? actual)
    {
        Assert.True(actual is not null, $"{where}: expected a return value {expected}, got none");
        switch (expected.ValueKind)
        {
            case JsonValueKind.True:
            case JsonValueKind.False:
                Assert.Equal(expected.GetBoolean(), (bool)actual!);
                break;
            case JsonValueKind.Number:
                Assert.Equal(expected.GetInt64(), Convert.ToInt64(actual, CultureInfo.InvariantCulture));
                break;
            case JsonValueKind.String:
                // a double, written by the harness as its exact decimal expansion
                double want = double.Parse(expected.GetString()!, CultureInfo.InvariantCulture);
                Assert.True(want.Equals((double)actual!), $"{where}: expected {expected.GetString()}, got {((double)actual!).ToString("R", CultureInfo.InvariantCulture)}");
                break;
            default:
                throw new InvalidOperationException("unexpected return kind " + expected.ValueKind);
        }
    }

    private static void CompareState(string where, JsonElement defaults, JsonElement sparse, NPoint actual)
    {
        List<string> errors = [];
        foreach (JsonProperty d in defaults.EnumerateObject())
        {
            JsonElement want = sparse.TryGetProperty(d.Name, out JsonElement s) ? s : d.Value;
            string propName = NPointScenarioHost.CSharpPropertyName(d.Name);
            PropertyInfo prop = typeof(NPoint).GetProperty(propName) ?? throw new InvalidOperationException("NPoint has no property " + propName + " (Java field " + d.Name + ")");
            object? got = prop.GetValue(actual);
            if (!Same(want, got))
            {
                errors.Add($"{d.Name}: Java {want} / port {Describe(got)}");
            }
        }

        Assert.True(errors.Count == 0, $"{where}: {errors.Count} field(s) differ\n" + string.Join("\n", errors));
    }

    private static bool Same(JsonElement want, object? got)
    {
        switch (want.ValueKind)
        {
            case JsonValueKind.True:
            case JsonValueKind.False:
                return got is bool b && b == want.GetBoolean();
            case JsonValueKind.Number:
                return got is not null and not bool && Convert.ToInt64(got, CultureInfo.InvariantCulture) == want.GetInt64();
            case JsonValueKind.Array:
                return got is List<int> list && list.SequenceEqual(want.EnumerateArray().Select(x => x.GetInt32()));
            default:
                throw new InvalidOperationException("unexpected state kind " + want.ValueKind);
        }
    }

    private static string Describe(object? v) => v is List<int> l ? "[" + string.Join(",", l) + "]" : Convert.ToString(v, CultureInfo.InvariantCulture) ?? "null";

    private static void CompareEffects(string where, JsonElement expected, NPointScenarioHost.Store store)
    {
        NPointFacts f = store.Facts;
        Assert.True(expected.GetProperty("worldcup").GetInt32() == f.SetClothes.Worldcup, $"{where}: worldcup Java {expected.GetProperty("worldcup")} / port {f.SetClothes.Worldcup}");
        JsonElement ta = expected.GetProperty("trainArmorId");
        if (ta.ValueKind == JsonValueKind.Null)
        {
            Assert.True(f.Inventory.TrainingArmor is null, $"{where}: Java left inventory.trainArmor null, the port set {f.Inventory.TrainingArmor?.TemplateId}");
        }
        else
        {
            Assert.True(f.Inventory.TrainingArmor is not null && f.Inventory.TrainingArmor.TemplateId == ta.GetInt32(), $"{where}: trainArmor Java {ta} / port {f.Inventory.TrainingArmor?.TemplateId}");
        }

        Assert.Equal(expected.GetProperty("isXChuong").GetBoolean(), f.EffectSkin.IsBlastDamageMultiplierReady);
        Assert.Equal(expected.GetProperty("isXDame").GetBoolean(), f.EffectSkin.IsBlastDamageMultiplierApplied);
        Assert.Equal(expected.GetProperty("isCharging").GetBoolean(), store.IsCharging);
        Assert.Equal(expected.GetProperty("countCharging").GetInt32(), store.CountCharging);
    }
